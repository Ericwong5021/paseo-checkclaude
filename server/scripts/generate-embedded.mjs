// Regenerates server/scripts/embedded.ts from the upstream shell scripts in this
// directory. Paseo bundles plugin server code into a single file, so the scripts
// travel as strings and are written to a cache directory at run time.
//
// Upstream: https://github.com/zzusec/CheckClaude (MIT)
// Run: npm run embed
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const scripts = [
  ["CLAUDE_CHECK_SH", "claude-check.sh"],
  ["AUTO_TIMEZONE_SH", "auto-timezone.sh"],
];

const lines = [
  "// Generated by server/scripts/generate-embedded.mjs. Do not edit by hand.",
  "// Upstream: https://github.com/zzusec/CheckClaude (MIT)",
  "",
];

for (const [constant, file] of scripts) {
  const source = await readFile(join(here, file), "utf8");
  lines.push(`export const ${constant} = ${JSON.stringify(source)};`, "");
}

await writeFile(join(here, "embedded.ts"), lines.join("\n"), "utf8");
console.log(`Wrote embedded.ts (${scripts.length} scripts)`);
