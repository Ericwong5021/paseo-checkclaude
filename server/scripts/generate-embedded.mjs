// Regenerates server/scripts/embedded.ts from the upstream shell scripts and the
// native browser probe. Paseo bundles plugin server code into a single file, so
// these assets travel as strings/binary blobs and are materialised on the daemon
// at run time.
//
// Sources:
//   claude-check.sh, auto-timezone.sh  https://github.com/zzusec/CheckClaude (MIT)
//   native/bin/ccprobe                 build with server/native/build.sh
//
// Run: npm run embed
import { readFile, writeFile } from "node:fs/promises";
import { gzipSync } from "node:zlib";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const scripts = [
  ["CLAUDE_CHECK_SH", "claude-check.sh"],
  ["AUTO_TIMEZONE_SH", "auto-timezone.sh"],
];

const lines = [
  "// Generated by server/scripts/generate-embedded.mjs. Do not edit by hand.",
  "// Sources: https://github.com/zzusec/CheckClaude (MIT) and server/native/main.swift",
  "",
];

for (const [constant, file] of scripts) {
  const source = await readFile(join(here, file), "utf8");
  lines.push(`export const ${constant} = ${JSON.stringify(source)};`, "");
}

const probe = await readFile(join(here, "..", "native", "bin", "ccprobe"));
const probeGzip = gzipSync(probe, { level: 9 });
lines.push(`/** Universal macOS binary built by server/native/build.sh, gzipped. */`);
lines.push(`export const PROBE_BINARY_GZIP_BASE64 = ${JSON.stringify(probeGzip.toString("base64"))};`, "");

await writeFile(join(here, "embedded.ts"), lines.join("\n"), "utf8");
console.log(
  `Wrote embedded.ts (${scripts.length} scripts, probe ${probe.length} bytes, ${probeGzip.length} gzipped)`,
);
